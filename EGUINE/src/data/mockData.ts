export function getChantSuggestion(chant: Chant): Chant[] {
  return chants
    .filter(
      (c) =>
        c.id !== chant.id &&
        (c.langue === chant.langue ||
          c.temps_liturgique === chant.temps_liturgique ||
          c.categorie === chant.categorie)
    )
    .slice(0, 3);
}
