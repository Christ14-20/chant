    action_grace: 'Thanksgiving',
    chant_final: 'Closing song',
    louange: 'Praise',
    adoration: 'Adoration',
    penitence: 'Penance',
    marial: 'Marian',
    funerailles: 'Funeral',
    autre: 'Other',
