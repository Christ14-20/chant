const translationTemplates = Object.entries(en)
  .filter(([template]) => template.includes('{{'))
  .map(([template, translation]) => ({
    translation,
    pattern: new RegExp(`^${template.split(/({{\w+}})/g).map((part) =>
      part.startsWith('{{') ? '(.+?)' : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    ).join('')}$`),
  }));

export function normalizeInterfaceLanguage(locale: string | null | undefined): InterfaceLanguage {
  return locale?.trim().toLowerCase().startsWith('en') ? 'en' : 'fr';
}

export function translate(
  source: string,
  language: InterfaceLanguage,
  variables?: Record<string, string | number>,
): string {
  if (language === 'fr') {
    return Object.entries(variables ?? {}).reduce(
      (value, [key, replacement]) => value.replaceAll(`{{${key}}}`, String(replacement)),
      source,
    );
  }

  const leading = source.match(/^\s*/)?.[0] ?? '';
  const trailing = source.match(/\s*$/)?.[0] ?? '';
  const key = source.trim();
  let translated = en[key];

  const ordinalDay = key.match(/^(\d+)(?:er|e) dimanche (de|du) (Carême|Pâques|l’Avent|l'Avent|Temps ordinaire)$/);
  if (!translated && ordinalDay) {
    const number = Number(ordinalDay[1]);
    const suffix = number % 100 >= 11 && number % 100 <= 13
      ? 'th'
      : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[number % 10] ?? 'th';
    const season = ordinalDay[3] === 'Carême'
      ? 'Lent'
      : ordinalDay[3] === 'Pâques'
        ? 'Easter'
        : ordinalDay[3].toLowerCase().includes('avent')
          ? 'Advent'
          : 'Ordinary Time';
    translated = `${number}${suffix} Sunday ${season === 'Ordinary Time' ? 'in' : 'of'} ${season}`;
  }

  if (!translated) {
    for (const { pattern, translation } of translationTemplates) {
      const match = key.match(pattern);
      if (!match) continue;
      const captures = match.slice(1).map((capture) => translate(capture, language));
      let captureIndex = 0;
      translated = translation.replace(/{{\w+}}/g, () => captures[captureIndex++] ?? '');
      break;
    }
  }
  translated ??= key;
  translated = Object.entries(variables ?? {}).reduce(
    (value, [name, replacement]) => value.replaceAll(`{{${name}}}`, String(replacement)),
    translated,
  );
  return `${leading}${translated}${trailing}`;
}

